-- Migrate any challan data from PI docs onto the SO's billing row, then delete
-- those PI rows (Challan doesn't use the PI list).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_name = 'order_billing_docs' AND column_name = 'challan_no') THEN
        INSERT INTO order_billing (order_id)
            SELECT DISTINCT d.order_id FROM order_billing_docs d
             JOIN orders o ON o.id = d.order_id
             WHERE o.bill_type = 'Challan' AND d.challan_no IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM order_billing b WHERE b.order_id = d.order_id);
        UPDATE order_billing b SET
            challan_no = COALESCE(b.challan_no, sub.challan_no),
            challan_date = COALESCE(b.challan_date, sub.challan_date),
            challan_value = COALESCE(b.challan_value, sub.challan_value),
            fr_reason = COALESCE(b.fr_reason, sub.fr_reason)
          FROM (
            SELECT DISTINCT ON (d.order_id) d.order_id, d.challan_no, d.challan_date,
                   d.challan_value, d.fr_reason
              FROM order_billing_docs d
              JOIN orders o ON o.id = d.order_id
             WHERE o.bill_type = 'Challan'
             ORDER BY d.order_id, d.seq
          ) sub
         WHERE b.order_id = sub.order_id;
        DELETE FROM order_billing_docs d USING orders o
         WHERE d.order_id = o.id AND o.bill_type = 'Challan';
    END IF;
END $$;

