        UPDATE order_accounts a SET
            payment_status = COALESCE(a.payment_status, (
              SELECT d.payment_status FROM order_billing_docs d
               WHERE d.order_id = a.order_id AND d.payment_status IS NOT NULL
               ORDER BY d.seq LIMIT 1)),
            payment_confirmed_date = COALESCE(a.payment_confirmed_date, (
              SELECT d.payment_confirmed_date FROM order_billing_docs d
               WHERE d.order_id = a.order_id AND d.payment_confirmed_date IS NOT NULL
               ORDER BY d.seq LIMIT 1)),
            amount_received = COALESCE(a.amount_received, (
              SELECT SUM(d.amount_received) FROM order_billing_docs d
               WHERE d.order_id = a.order_id));
    END IF;
END $$;

